# -*- coding: utf-8 -*-
"""e1 光センサーの配線図。

10kΩ の固定抵抗のかわりに **10kΩ の可変抵抗**を入れてある。
こうすると、章の途中で配線を組みかえずに

  ・いっぱいに回す（＝10kΩ）… 明るさで点滅の速さが変わるのを見る
  ・少し もどす            … 室内でぎりぎり消えるさかいめを作る

の両方ができる。つまみは **まん中の足と、片はしの足**の2本だけ使う。

**つまみの位置は b4 と同じ 26〜28列**（2026-10-24）。b4 の配線から続けると、
  そのまま … A2 のオレンジ（6列 → 27列＝まん中）、28列の黒（→ −レール）、
             ボードの GND の線、LED
  変える   … 5V の赤い線の右はしを 26列 → 20列
  足す     … CdS（20・21列）と、21列 → 27列 のオレンジ
つまみの左はし（26列）は何にもつながない。使うのは まん中（27）と 右はし（28）。
⚠ b4 以前の配置（左はしと まん中を使う）とは、10kΩ になる回す向きが逆になる。
"""
import sys
sys.path.insert(0, "tools")
sys.stdout.reconfigure(encoding="utf-8")
from bb import *

RED, ORANGE, BLACK = (214, 60, 50), (240, 150, 40), (40, 44, 48)

im, d = new("光センサー（CdS）と つまみ をつなぐ")
board(d)
mcu(d)

wire(d, (2, "j"), (2, "-t"), BLACK)        # ボードのGND → −レール（b4 と同じ）

# 5V ── CdS ── A2 ── つまみ（まん中〜右はし）── GND
vr(d, 26, "h")                             # 足は 26・27・28列（まん中が27）。b4 と同じ場所
cds(d, 20, "f")                            # 足は 20列・21列（つまみから離して見やすく）
wire(d, (1, "h"), (20, "h"), RED)          # 5V → CdS の左の足（h行。i行のオレンジと一直線に見えないように）
wire(d, (21, "i"), (27, "i"), ORANGE)      # CdS の右の足 → まん中（27列）。i行を水平に
wire(d, (6, "j"), (27, "j"), ORANGE)       # A2 → まん中（b4 と同じ線）
wire(d, (28, "j"), (28, "-t"), BLACK)      # 右はし → −レール（b3・b4 と同じ線）

# LED（基本編と同じ 16・17列）
wire(d, (8, "a"), (16, "a"), RED)          # 5番 → LED
led(d, 16, "c", note=False)
resistor_v(d, 17, "a", "-b")
wire(d, (3, "a"), (3, "-b"), BLACK)        # ボードのGND → 下の −レール
save(im, "e1_light", "bb_cds.png")
